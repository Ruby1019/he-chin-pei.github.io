function applyLanguage(language) {
  const dictionary = translations[language] || translations.en;

  bindings.forEach(([key, selector, mode]) => {
    const element = document.querySelector(selector);
    if (!element || !dictionary[key]) return;
    if (mode === "html") {
      element.innerHTML = dictionary[key];
    } else {
      element.textContent = dictionary[key];
    }
  });

  const toggle = document.querySelector(".language-toggle");
  document.documentElement.lang = language === "zh" ? "zh-Hant" : "en";
  toggle.textContent = language === "zh" ? "English" : "中文";
  toggle.setAttribute("aria-pressed", language === "zh" ? "true" : "false");
  localStorage.setItem("preferredLanguage", language);
}

document.addEventListener("DOMContentLoaded", () => {
  const toggle = document.querySelector(".language-toggle");
  const savedLanguage = localStorage.getItem("preferredLanguage");
  const initialLanguage = savedLanguage === "zh" ? "zh" : "en";

  applyLanguage(initialLanguage);

  toggle.addEventListener("click", () => {
    const nextLanguage = document.documentElement.lang === "zh-Hant" ? "en" : "zh";
    applyLanguage(nextLanguage);
  });
});